-- 已通过问题转换为知识审批单时，保存知识关联和可追溯的回归测试用例。
ALTER TABLE learning.learning_problem
    ADD COLUMN converted_knowledge_id BIGINT,
    ADD COLUMN converted_version_id BIGINT,
    ADD COLUMN converted_approval_id BIGINT,
    ADD COLUMN converted_by VARCHAR(64),
    ADD COLUMN converted_at TIMESTAMPTZ,
    ADD CONSTRAINT fk_learning_problem_converted_knowledge FOREIGN KEY (converted_knowledge_id)
        REFERENCES business.kb_knowledge (id),
    ADD CONSTRAINT fk_learning_problem_converted_version FOREIGN KEY (converted_version_id)
        REFERENCES business.kb_knowledge_version (id),
    ADD CONSTRAINT fk_learning_problem_converted_approval FOREIGN KEY (converted_approval_id)
        REFERENCES business.kb_approval (id);

-- 动作6表示“提交知识草稿审批”。
ALTER TABLE learning.learning_problem_review
    DROP CONSTRAINT ck_learning_problem_review_action,
    ADD CONSTRAINT ck_learning_problem_review_action CHECK (action_type IN (1, 2, 3, 4, 5, 6));

CREATE TABLE learning.learning_evaluation_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_code VARCHAR(64) NOT NULL,
    problem_id BIGINT NOT NULL,
    knowledge_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    case_no INTEGER NOT NULL,
    question_text TEXT NOT NULL,
    expected_answer TEXT NOT NULL,
    expected_intent VARCHAR(64) NOT NULL,
    case_type SMALLINT NOT NULL DEFAULT 1,
    status SMALLINT NOT NULL DEFAULT 0,
    generated_provider VARCHAR(64) NOT NULL,
    generated_model VARCHAR(128) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    approved_by VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMPTZ,
    processed_at TIMESTAMPTZ,
    CONSTRAINT uk_learning_evaluation_case_code UNIQUE (case_code),
    CONSTRAINT uk_learning_evaluation_version_no UNIQUE (version_id, case_no),
    CONSTRAINT fk_learning_evaluation_problem FOREIGN KEY (problem_id)
        REFERENCES learning.learning_problem (id),
    CONSTRAINT fk_learning_evaluation_version_knowledge FOREIGN KEY (version_id, knowledge_id)
        REFERENCES business.kb_knowledge_version (id, knowledge_id),
    CONSTRAINT ck_learning_evaluation_case_no CHECK (case_no >= 0),
    CONSTRAINT ck_learning_evaluation_case_type CHECK (case_type IN (1, 2)),
    CONSTRAINT ck_learning_evaluation_status CHECK (status IN (0, 1, 2, 3))
);

CREATE INDEX idx_learning_evaluation_status_created
    ON learning.learning_evaluation_case (status, created_at DESC, id DESC);
CREATE INDEX idx_learning_evaluation_problem
    ON learning.learning_evaluation_case (problem_id, id);

COMMENT ON TABLE learning.learning_evaluation_case IS '由人工审核问题生成并随知识审批生效的回归测试用例';
COMMENT ON COLUMN learning.learning_evaluation_case.status IS '0待知识审批、1已生效、2审批驳回、3已归档';
COMMENT ON COLUMN learning.learning_evaluation_case.case_type IS '1知识正样本、2困难负样本';

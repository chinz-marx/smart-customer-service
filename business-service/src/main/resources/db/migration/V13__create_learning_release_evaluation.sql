-- 知识经人工审核后先进入自动发布验收，只有通过后才成为正式线上版本。
ALTER TABLE business.kb_knowledge_version
    DROP CONSTRAINT ck_kb_version_status,
    ADD CONSTRAINT ck_kb_version_status CHECK (version_status IN (0, 1, 2, 3, 4, 5));

COMMENT ON COLUMN business.kb_knowledge_version.version_status IS
    '0草稿、1待人工审批、2已发布、3已驳回、4已归档、5待自动验收';

-- 测试用例状态改为：人工审批和自动验收分成两个明确阶段。
-- V12 中 1 表示已生效；先迁到新枚举的 3，再把 1 留给待自动验收。
UPDATE learning.learning_evaluation_case
SET status = 3
WHERE status = 1;

COMMENT ON COLUMN learning.learning_evaluation_case.status IS
    '0待知识审批、1待自动验收、2已驳回、3已生效';

CREATE TABLE learning.learning_evaluation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_no VARCHAR(64) NOT NULL,
    problem_id BIGINT NOT NULL,
    knowledge_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    approval_id BIGINT NOT NULL,
    status SMALLINT NOT NULL DEFAULT 0,
    retry_count INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_cases INTEGER NOT NULL DEFAULT 0,
    recall_at_1 DOUBLE PRECISION,
    recall_at_3 DOUBLE PRECISION,
    threshold_recall DOUBLE PRECISION,
    error_count INTEGER,
    average_latency_ms DOUBLE PRECISION,
    p95_latency_ms DOUBLE PRECISION,
    distance_threshold DOUBLE PRECISION,
    metrics JSONB,
    error_message VARCHAR(1000),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    CONSTRAINT uk_learning_evaluation_run_no UNIQUE (run_no),
    CONSTRAINT uk_learning_evaluation_run_version UNIQUE (version_id),
    CONSTRAINT fk_learning_evaluation_run_problem FOREIGN KEY (problem_id)
        REFERENCES learning.learning_problem (id),
    CONSTRAINT fk_learning_evaluation_run_version_knowledge FOREIGN KEY (version_id, knowledge_id)
        REFERENCES business.kb_knowledge_version (id, knowledge_id),
    CONSTRAINT fk_learning_evaluation_run_approval FOREIGN KEY (approval_id)
        REFERENCES business.kb_approval (id),
    CONSTRAINT ck_learning_evaluation_run_status CHECK (status IN (0, 1, 2, 3, 4)),
    CONSTRAINT ck_learning_evaluation_run_retry CHECK (retry_count >= 0)
);

CREATE TABLE learning.learning_evaluation_case_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    case_id BIGINT NOT NULL,
    passed_at_1 BOOLEAN NOT NULL,
    passed_at_3 BOOLEAN NOT NULL,
    passed_threshold BOOLEAN NOT NULL,
    top_knowledge_id BIGINT,
    top_version_id BIGINT,
    top_chunk_no INTEGER,
    top_distance DOUBLE PRECISION,
    latency_ms DOUBLE PRECISION NOT NULL,
    error_message VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_learning_evaluation_case_result UNIQUE (run_id, case_id),
    CONSTRAINT fk_learning_evaluation_result_run FOREIGN KEY (run_id)
        REFERENCES learning.learning_evaluation_run (id) ON DELETE CASCADE,
    CONSTRAINT fk_learning_evaluation_result_case FOREIGN KEY (case_id)
        REFERENCES learning.learning_evaluation_case (id)
);

CREATE INDEX idx_learning_evaluation_run_ready
    ON learning.learning_evaluation_run (status, next_retry_at, id)
    WHERE status IN (0, 1);
CREATE INDEX idx_learning_evaluation_run_created
    ON learning.learning_evaluation_run (created_at DESC, id DESC);
CREATE INDEX idx_learning_evaluation_result_run
    ON learning.learning_evaluation_case_result (run_id, id);

COMMENT ON TABLE learning.learning_evaluation_run IS
    '知识候选版本的自动发布验收批次，状态：0待执行、1执行中、2通过、3业务验收失败、4系统失败';
COMMENT ON TABLE learning.learning_evaluation_case_result IS
    '自动发布验收的逐用例召回结果';
